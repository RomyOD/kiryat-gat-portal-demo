for (did, divi, div, dn) in depts:
    ndept = len(STRUCTURE[divi-1][1])
    dtotal = TOTAL_EXPENSE * WEIGHT.get(div, small) / wsum / ndept
    lines = SPECIAL_EXP.get(dn, []) + EXP_LINES[: (4 if dtotal > 8e6 else 3)]
    shares = [random.uniform(0.6, 1.6) for _ in lines]
    shares[len(SPECIAL_EXP.get(dn, []))] *= 2.2  # salaries are the largest line
    ssum = sum(shares)
    seq = 100
    for ln, sh in zip(lines, shares):
        b26 = round(dtotal * sh / ssum, -3)
        a25 = round(b26 * random.uniform(0.9, 1.04), -2)
        pace = random.uniform(0.66, 0.8)
        commit = round(b26 * random.uniform(0.02, 0.14), -2)
        if random.random() < 0.09: pace = random.uniform(0.9, 1.05)  # overrun
        a26 = round(b26 * pace, -2)
        seq += 10; item_id += 1
        code = f"2-{divi:02d}{dept_id_local if False else ''}"  # placeholder
        code = f"2-{divi:02d}-{(did % 100):02d}-{seq}"
        name = ln if ln not in EXP_LINES else f"{ln} - {dn}"
        budget_rows.append((item_id, code, name, "הוצאה", did, a25, b26, a26, commit))
        items_by_dept.setdefault(did, []).append((item_id, ln))
